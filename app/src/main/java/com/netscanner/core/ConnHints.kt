        389, 636 -> "LDAP: ldap://$ip"
        443 -> "https://$ip"
        445 -> "SMB: smb://$ip/share · Windows: \\\\$ip\\share"
        465 -> "SMTPS: $ip:465"
        515 -> "LPD print: lpd://$ip/PASSTHRU"
